package utils;

public class Animal {
	//private
	private String name;
	private double body;
	private int speed;
	
	//getter
	public String getName() {
		return this.name;
	}
	
	//setter
	public void setName( String name ) {
		this.name = name;
	}
	
	//getter
	public double getBody() {
		return this.body;
	}
	
	//setter
	public void setBody( double body ) {
		this.body = body;
	}
	
	//getter
	public int getSpeed() {
		return this.speed;
	}
	
	//setter
	public void setSpeed( int speed ) {
		this.speed = speed;
	}

}
